    //  ___ For Reschedule Of Appointment ___ // 
    public static function update_appointment_schedule(string $patient_doc_id, string $appointmentid, string $slotid): bool {

        // Appointment Record Path
        $path = Database::ACCOUNT_USER . "/" . $patient_doc_id . "/" . Database::APPOINTMENT_RECORD;

        if ($appointmentid !== null):

            $db = new DbQuery();
            $doc_ref = $db->get_db()->collection($path)->document($appointmentid);

            # Update Appointment Slot ID
            $trnx_result = $db->get_db()->runTransaction(function (Transaction $transaction) use ($doc_ref, $slotid) {
                $snapshot = $transaction->snapshot($doc_ref);
                $db_slotid = $snapshot['slotid'];
                if ($db_slotid !== $slotid):
                    $transaction->update($doc_ref, [
                        ['path' => 'slotid', 'value' => $slotid],
                        ['path' => 'appointmentstatus', 'value' => Appointment_Status::UPCOMING]
                    ]);
                    return true;
                endif;
                return false;
            });
        endif;

        return $trnx_result;
    }

    // -- REMOVE APPOINTMENT RECORD
    public static function remove_appointment_record(string $patient_doc_id, string $appointmentid): Appointment_Record {

        $db = new DbQuery();

        # Update The Patient's Appointment Record (DELETE APPOINTMENT RECORD)
        $user_appt_path = Database::ACCOUNT_USER . "/" . $patient_doc_id . "/" . Database::APPOINTMENT_RECORD;

        # Get Appt Details (slotid)
        $appt = $db->get_db()->collection($user_appt_path)->document($appointmentid);

        if ($appt->snapshot()->exists()):

            # Retrieving The Data Before Deletion
            $appt_details = $appt->snapshot()->data();

            # Appointment Record Object
            $appt_obj = self::initialise_appointment_record($appt_details);

            # Delete The Appointment Record
            $appt->delete();

            return $appt_obj;
        endif;
    }

