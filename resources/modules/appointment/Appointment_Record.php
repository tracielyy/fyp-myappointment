    // -- CREATE APPOINTMENT RECORD
    public static function create_appointment_record(string $user_doc_id, array $booking_info): ?Appointment_Record {

        $db = new DbQuery();

        # SET Appointment Creation Time
        $createdon = new Time();

        # Get Appointment ID
        $id = self::generate_appointment_id($user_doc_id);

        # Add The AppointmentRecord As Sub Collection Nested In Patient Database
        $appt_doc_path = Database::ACCOUNT_USER . "/" . $user_doc_id . "/" . Database::APPOINTMENT_RECORD;
        $batch = $db->get_db()->batch();

        $appt_record_arr = array(
            'appointmentid' => $id,
            'appointmenttype' => $booking_info['appointmenttype'],
            'appointmentstatus' => Appointment_Status::UPCOMING,
            'facilityid' => $booking_info['facilityid'],
            'createdon' => ['date' => $createdon->get_date(), 'time' => $createdon->get_time()],
            'slotid' => $booking_info['slotid'],
            'mrid' => ''
        );

        $batch->set($db->get_db()->collection($appt_doc_path)->document($id), $appt_record_arr);
        $batch->commit();

        return self::initialise_appointment_record($appt_record_arr);
    }

    public static function set_mrid(string $patientid, string $slotid, string $mrid): bool {
        $db = new DbQuery();
        $doc_path = Database::ACCOUNT_USER . "/" . $patientid . "/" . Database::APPOINTMENT_RECORD;
        $documents = $db->get_db()->collection($doc_path)->where('slotid', "=", $slotid)->where("mrid", "!=", "")->documents();
        foreach ($documents as $doc):
            if ($doc->exists()):
                $appt_id = $doc->id(); // Finding The Appt ID
                break;
            endif;
        endforeach;

        // Use The Appt ID & Set The mrid 
        if ($appt_id !== null):
            $doc_ref = $db->get_db()->collection($doc_path)->document($appt_id);
            $trxn_result = $db->get_db()->runTransaction(function (Transaction $transaction) use ($doc_ref, $mrid) {
                $snapshot = $transaction->snapshot($doc_ref);
                $db_mrid = $snapshot['mrid'];
                if ($db_mrid == ""):
                    $transaction->update($doc_ref, [['path', 'mrid', 'value', $mrid]]);
                    return true;
                endif;
                return false;
            });
            return $trxn_result;
        endif;
        return false;
    }

    // -- Validate Appointment Booking  (Check If Patient Have Same Appointment) -- //
    public static function validate_appt_booking(string $user_doc_id, array $booking_info): null|bool {

        # Search For Same Appointment
        if ($booking_info['slotid'] !== null || !empty($booking_info['slotid'])):
            $booking_date = explode("~", $booking_info['slotid'])[1];
            $db = new DbQuery();
            $path = Database::ACCOUNT_USER . "/" . $user_doc_id . "/" . Database::APPOINTMENT_RECORD;
            $snapshot = $db->get_db()->collection($path)
                            ->where("appointmentstatus", "=", Appointment_Status::UPCOMING)
                            ->where("appointmenttype", "=", $booking_info['appointmenttype'])->documents();

            # Loop & Check If There Is Any Match
            foreach ($snapshot as $doc):
                if ($doc->exists()):
                    $comparison_date = explode("~", $doc->data()['slotid'])[1];
                    # Check If Have Same Appointment Type In The Same Day
                    if ($comparison_date == $booking_date):
                        return False;
                    endif;

                endif;

            endforeach;
            return True;
        endif;
        return null;
    }

    // -- User-Defined ID -- //
    private static function generate_appointment_id(string $user_doc_id) {

        # To OrderBy The Appointment ID
        $orderBy = array('appointmentid');

        # Find The Last ID & Increment
        $db = new DbQuery();
        $doc_path = Database::ACCOUNT_USER . "/" . $user_doc_id . "/" . Database::APPOINTMENT_RECORD;
        $last_id_appointment = $db->get_first_id_ordered($doc_path, $orderBy, false);

        # If There Is Any Present ID In Database
        $current_year = Time::get_current_year();
        if ($last_id_appointment != null) :

            $last_id = explode("-", $last_id_appointment);

            # Compare Year
            if ($last_id[1] == $current_year):

                # Increase The Number
                $new_id = ++$last_id[2];

                return $last_id[0] . "-" . $last_id[1] . "-" . $new_id; # -- There is A Current Year Id
            endif;

            return $last_id[0] . "-" . $current_year . "-1000"; # -- There Is No Current Year Id

        endif;
        return "appt-" . $current_year . "-1000"; # -- Totally No ID Present In Database
    }

    // -- Retrieve Of Appointment Records Of Certain Type -- //
    private static function retrieve_patient_appointment(array $email, ?array $appointmentstatus = NULL): array {

        # Array Of Appointments
        $appointment_arr = array();

        # Query For Upcoming Appointment Records
        $db = new DbQuery();

        $doc_id = $db->get_document_id(Database::ACCOUNT_USER, $email);
        $doc_path = Database::ACCOUNT_USER . "/" . $doc_id . "/" . Database::APPOINTMENT_RECORD;

        # Check If Need To Filter By Appointment Status
        if ($appointmentstatus == NULL):
            $record_list = $db->get_documents_by_path($doc_path, False);
        else:
            $record_list = $db->get_documents_by_path($doc_path, True, $appointmentstatus);
        endif;

        # Create Appointment Record Object List
        foreach ($record_list as $record) :

            $appointment_arr[] = self::initialise_appointment_record($record);

        endforeach;
        usort($appointment_arr, array("Appointment_Record", "cmp_obj"));

        return $appointment_arr;
    }

